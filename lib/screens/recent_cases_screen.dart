        ),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            _buildCaseHeader(chatCase, isDark),
            const SizedBox(height: 16),

            if (isSessionData && sessionId != null) ...[
              _buildSessionContent(chatCase, sessionId, isDark),
            ] else ...[
