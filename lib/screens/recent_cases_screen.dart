class RecentCasesScreen extends StatefulWidget {
  final List<Map<String, dynamic>> recentCases;
  final VoidCallback onCaseUpdated;

  const RecentCasesScreen({
    super.key,
    required this.recentCases,
    required this.onCaseUpdated,
  });

  @override
  State<RecentCasesScreen> createState() => _RecentCasesScreenState();
}

class _RecentCasesScreenState extends State<RecentCasesScreen> {
  final DatabaseService _databaseService = DatabaseService();
  List<Map<String, dynamic>> _recentCases = [];
  bool _isLoading = false;
  String _selectedCategory = 'All';

  // Cache for expanded conversation details
  Map<String, List<Map<String, dynamic>>> _conversationCache = {};
  Set<String> _expandedSessions = {};

  @override
  void initState() {
    super.initState();
    _recentCases = List.from(widget.recentCases);
    _debugPrintCategories();
  }

  void _debugPrintCategories() {
    final categories = _recentCases
        .map((chatCase) => _getCategoryFromCase(chatCase))
        .toSet()
        .toList();
    print('Actual categories in recent cases: $categories');
  }

  // Helper method to get category from either data format
  String _getCategoryFromCase(Map<String, dynamic> chatCase) {
    if (chatCase.containsKey('category')) {
      return chatCase['category']?.toString() ?? 'General';
    } else if (chatCase.containsKey('categories')) {
      final categories = chatCase['categories'] as List<dynamic>?;
      return categories?.isNotEmpty == true ? categories!.first.toString() : 'General';
    }
    return 'General';
  }

  // Check if this is session data
  bool _isSessionData(Map<String, dynamic> chatCase) {
    return chatCase.containsKey('first_question') &&
        chatCase.containsKey('session_id') &&
        chatCase['session_id'] != null;
  }

  // Get session ID for session data
  String? _getSessionId(Map<String, dynamic> chatCase) {
    if (_isSessionData(chatCase)) {
      return chatCase['session_id']?.toString();
    }
    return null;
  }

  // Fetch conversation details for a session
  Future<List<Map<String, dynamic>>> _fetchConversationDetails(String sessionId) async {
    if (_conversationCache.containsKey(sessionId)) {
      return _conversationCache[sessionId]!;
    }

    try {
      final messages = await _databaseService.getSessionMessages(sessionId);
      messages.sort((a, b) {
        final aTime = a['created_at']?.toString();
        final bTime = b['created_at']?.toString();
        if (aTime == null || bTime == null) return 0;
        try {
          return DateTime.parse(aTime).compareTo(DateTime.parse(bTime));
        } catch (e) {
          return 0;
        }
      });

      _conversationCache[sessionId] = messages;
      return messages;
    } catch (e) {
      print('Error fetching conversation details for session $sessionId: $e');
      return [];
    }
  }

  // NEW: Share individual Q&A pair
  Future<void> _shareQAPair(String question, String answer, String category, String createdAt) async {
    try {
      final shareText = '''
📋 Legal Q&A from LawBot

❓ Question:
$question

🤖 LawBot Answer:
$answer

📂 Category: $category
⏰ ${createdAt.isNotEmpty ? PhilippineTime.formatChatHistoryTime(createdAt) : 'Unknown date'}

---
Generated by LawBot - Your AI Legal Assistant for Philippine Cybercrime Laws
      ''';

      await Share.share(
        shareText.trim(),
        subject: 'Legal Q&A from LawBot',
      );
    } catch (e) {
      print('Error sharing Q&A: $e');
      _showSnackBar('Failed to share Q&A. Please try again.', Colors.red);
    }
  }

  // NEW: Save individual Q&A pair
  Future<void> _saveQAPair(String question, String answer, String category, List<String>? keywords) async {
    if (FirebaseAuth.instance.currentUser == null) {
      _showSignInRequiredDialog();
      return;
    }

    try {
      // Check if already saved
      final isAlreadySaved = await _databaseService.isAdviceSaved(question, answer);

      if (isAlreadySaved) {
        _showSnackBar('This Q&A is already saved!', Colors.orange);
        return;
      }

      await _databaseService.saveAdvice(
        question: question,
        answer: answer,
        category: category,
        tags: keywords,
      );

      _showSnackBar('Q&A saved to your bookmarks!', Colors.green);
    } catch (e) {
      print('Error saving Q&A: $e');
      _showSnackBar('Failed to save Q&A. Please try again.', Colors.red);
    }
  }

