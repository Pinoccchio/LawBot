  Widget _buildCaseHeader(Map<String, dynamic> chatCase, bool isDark) {
    String category;
    String createdAt;
    double? confidenceScore;

    if (chatCase.containsKey('question')) {
      category = chatCase['category'] ?? 'General';
      createdAt = chatCase['created_at'] ?? '';
      confidenceScore = chatCase['confidence_score'] as double?;
    } else {
      final categories = chatCase['categories'] as List<dynamic>?;
      category = categories?.isNotEmpty == true ? categories!.first.toString() : 'General';
      createdAt = chatCase['first_created_at'] ?? chatCase['last_created_at'] ?? '';
      confidenceScore = chatCase['avg_confidence'] as double?;
    }

    return Row(
      children: [
        Flexible(
          flex: 2,
          child: Container(
            padding: const EdgeInsets.symmetric(horizontal: 10, vertical: 6),
            decoration: BoxDecoration(
              gradient: LinearGradient(
                colors: isDark
                    ? [const Color(0xFF3B82F6), const Color(0xFF1D4ED8)]
                    : [const Color(0xFF2563EB), const Color(0xFF1D4ED8)],
              ),
              borderRadius: BorderRadius.circular(12),
            ),
            child: Text(
              category,
              style: const TextStyle(
                fontSize: 12,
                color: Colors.white,
                fontWeight: FontWeight.w600,
              ),
              overflow: TextOverflow.ellipsis,
              maxLines: 1,
            ),
          ),
        ),
        const SizedBox(width: 8),
        Flexible(
          flex: 3,
          child: Row(
            mainAxisAlignment: MainAxisAlignment.end,
            children: [
              if (confidenceScore != null) ...[
                Container(
                  padding: const EdgeInsets.symmetric(horizontal: 6, vertical: 4),
                  decoration: BoxDecoration(
                    color: confidenceScore > 0.8
                        ? Colors.green.withOpacity(0.1)
                        : confidenceScore > 0.6
                        ? Colors.orange.withOpacity(0.1)
                        : Colors.grey.withOpacity(0.1),
                    borderRadius: BorderRadius.circular(8),
                    border: Border.all(
                      color: confidenceScore > 0.8
                          ? Colors.green
                          : confidenceScore > 0.6
                          ? Colors.orange
                          : Colors.grey,
                      width: 1,
                    ),
                  ),
                  child: Row(
                    mainAxisSize: MainAxisSize.min,
                    children: [
                      Icon(
                        Icons.verified_rounded,
                        size: 10,
                        color: confidenceScore > 0.8
                            ? Colors.green
                            : confidenceScore > 0.6
                            ? Colors.orange
                            : Colors.grey,
                      ),
                      const SizedBox(width: 2),
                      Text(
                        '${(confidenceScore * 100).round()}%',
                        style: TextStyle(
                          fontSize: 9,
